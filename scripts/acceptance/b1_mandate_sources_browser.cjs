const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const { randomUUID } = require('node:crypto');
const { chromium } = require(process.env.HV_PLAYWRIGHT_PACKAGE);
const base = 'http://127.0.0.1:13000', output = '/tmp/hv-b1-mandate-acceptance';
(async () => {
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: process.env.HV_CHROMIUM_EXECUTABLE });
  const admin = await browser.newPage(), page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(15000);
  const report = { checks: [], pageErrors: [] };
  page.on('pageerror', e => report.pageErrors.push(e.message));
  const login = async (tab, email) => {
    await tab.goto(base + '/login'); await tab.getByLabel('E-Mail').fill(email); await tab.getByLabel('Passwort').fill('testpass1234');
    await tab.getByRole('button', { name: 'Anmelden', exact: true }).click(); await tab.waitForURL(u => !u.pathname.includes('login'));
  };
  const post = async (path, data, keyed = false, status = 201) => {
    const r = await admin.request.post(base + path, { data, headers: keyed ? { 'Idempotency-Key': randomUUID() } : {} });
    assert.equal(r.status(), status, await r.text()); return status === 204 ? null : r.json();
  };
  try {
    await login(admin, 'admin@alpha.de');
    const clerk = (await (await admin.request.get(base + '/api/users/page?eligible_for_scope=true&q=clerk%40alpha.de')).json()).items[0];
    const mandate = await post('/api/mandates', { mandate_type: 'WEG', label: 'Scoped mandate QA ' + Date.now(), start_date: '2024-01-01' });
    const property = await post('/api/properties', { name: 'Source QA property', street: 'Test 1', zip_code: '12345', city: 'Test', management_type: 'WEG' });
    const scope = await post('/api/accounting-scopes', { property_id: property.id, management_mandate_id: mandate.id, scope_type: 'WEG', label: 'Reviewed source scope', valid_from: '2025-01-01', whole_property: true, units: [] }, true);
    let grant = await post(`/api/accounting-scopes/${scope.id}/grants`, { user_id: clerk.id, capabilities: ['read', 'prepare'], reason: 'Synthetic source reviewer' }, true);
    await login(page, 'clerk@alpha.de');
    await page.goto(base + '/mandate/' + mandate.id);
    await page.getByRole('heading', { name: 'Zugängliche Dokumente', exact: true }).waitFor();
    await page.getByText(/keine vollständige Mandatsakte/).waitFor();
    const selector = page.getByRole('combobox', { name: 'Bereich für neuen Upload (optional)', exact: true });
    await selector.selectOption(scope.id);
    await page.getByLabel('Begründung der Bereichszuordnung', { exact: true }).fill('Gesamter Dateiinhalt für diesen Bereich geprüft');
    await page.getByLabel('Bezeichnung', { exact: true }).fill('Scoped source contract');
    const bytes = Buffer.from('%PDF-1.4 synthetic original mandate contract');
    await page.locator('input[type=file]').setInputFiles({ name: 'contract.pdf', mimeType: 'application/pdf', buffer: bytes });
    const endpoint = `/api/mandates/${mandate.id}/documents`;
    const response = page.waitForResponse(r => new URL(r.url()).pathname === endpoint && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Hochladen', exact: true }).click();
    const uploaded = await response; assert.equal(uploaded.status(), 201, await uploaded.text()); const doc = await uploaded.json();
    assert.equal(doc.accounting_scope_id, scope.id);
    await page.getByText('Scoped source contract', { exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Löschen', exact: true }).count(), 0);
    const download = endpoint + '/' + doc.id + '/download';
    assert.equal((await page.request.get(base + download)).status(), 404);
    assert.deepEqual(await (await admin.request.get(base + endpoint)).json(), []);
    report.checks.push('explicit same-mandate scope and review reason persist with the upload; listing is accessible-only and administration alone cannot see it');
    await post(`/api/accounting-scopes/${scope.id}/grants/${grant.id}/revoke`, {}, false, 204);
    grant = await post(`/api/accounting-scopes/${scope.id}/grants`, { user_id: clerk.id, capabilities: ['read', 'prepare', 'export'], reason: 'Synthetic reviewed export' }, true);
    const exported = await page.request.get(base + download); assert.equal(exported.status(), 200); assert.deepEqual(await exported.body(), bytes);
    await page.getByRole('button', { name: 'Archivieren', exact: true }).click();
    await page.getByLabel('Begründung der Archivierung', { exact: true }).fill('Durch neue Vertragsfassung ersetzt');
    await page.getByRole('button', { name: 'Archivierung speichern', exact: true }).click();
    await page.getByText('Keine zugänglichen Unterlagen für diese Auswahl.', { exact: true }).waitFor();
    await page.getByLabel('Archivierte Unterlagen anzeigen', { exact: true }).check();
    await page.getByText('Scoped source contract', { exact: true }).waitFor();
    await page.getByText('Archiviert · Durch neue Vertragsfassung ersetzt', { exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Archivieren', exact: true }).count(), 0);
    assert.deepEqual(await (await page.request.get(base + download)).body(), bytes);
    report.checks.push('export needs an additional exact grant; archive retains the original bytes and review history and removes the active-row archive action');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForFunction(() => document.querySelector('aside').getBoundingClientRect().right <= 1);
    await page.getByText('Scoped source contract', { exact: true }).scrollIntoViewIfNeeded();
    report.mobile = await page.locator('main').evaluate(n => ({ visible: n.clientWidth, content: n.scrollWidth })); assert.ok(report.mobile.content <= report.mobile.visible + 1);
    await page.screenshot({ path: output + '/mandate-mobile.png' });
    await page.route('**' + endpoint + '?*', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Synthetic list interruption' }) }));
    await page.getByRole('button', { name: 'Unterlagen neu laden', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Unterlagen derzeit nicht verfügbar' }).waitFor();
    assert.equal(await page.getByText('Scoped source contract', { exact: true }).count(), 0);
    assert.equal(await page.getByText('Keine zugänglichen Unterlagen für diese Auswahl.', { exact: true }).count(), 0);
    await page.unroute('**' + endpoint + '?*');
    await post(`/api/accounting-scopes/${scope.id}/grants/${grant.id}/revoke`, {}, false, 204);
    assert.equal((await page.request.get(base + download)).status(), 404);
    await page.getByRole('button', { name: 'Unterlagen neu laden', exact: true }).click();
    await page.getByText('Keine zugänglichen Unterlagen für diese Auswahl.', { exact: true }).waitFor();
    report.checks.push('failed reload hides stale documents without an empty success claim; later revocation blocks archived downloads and removes source rows');
    assert.deepEqual(report.pageErrors, []); report.status = 'passed';
  } finally {
    if (report.status !== 'passed') await page.screenshot({ path: output + '/failed-state.png', fullPage: true });
    await fs.writeFile(output + '/browser-report.json', JSON.stringify(report, null, 2)); await browser.close();
  }
  console.log(JSON.stringify(report));
})().catch(e => { console.error(e); process.exitCode = 1; });
