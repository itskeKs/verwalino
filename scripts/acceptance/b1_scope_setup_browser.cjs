/* Synthetic local-only scope setup acceptance. Uses API18000/Vite13000 and the
 * disposable DB55432 seed. Runtime paths must refer to existing installations. */
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { chromium } = require(process.env.HV_PLAYWRIGHT_PACKAGE || 'playwright');
const base = 'http://127.0.0.1:13000';
const output = process.env.HV_ACCEPTANCE_OUTPUT || '/tmp/hv-b1-scope-acceptance';
(async () => {
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: process.env.HV_CHROMIUM_EXECUTABLE });
  const report = { checks: [], pageErrors: [], failedResponses: [], initialUnauthenticatedChecks: 0 };
  let authenticated = false;
  let page;
  try {
    page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.on('pageerror', error => report.pageErrors.push(error.message));
    page.on('response', response => {
      if (!authenticated && response.status() === 401 && response.url().endsWith('/api/auth/session')) report.initialUnauthenticatedChecks++;
      else if (response.status() >= 400) report.failedResponses.push([response.status(), response.url()]);
    });
    await page.goto(base + '/login');
    await page.getByLabel('E-Mail').fill('admin@alpha.de');
    await page.getByLabel('Passwort').fill('testpass1234');
    await page.getByRole('button', { name: 'Anmelden', exact: true }).click();
    await page.waitForURL(url => !url.pathname.includes('login'));
    authenticated = true;
    const createdProperty = await page.request.post(base + '/api/properties', { data: { name: 'Scope browser acceptance', street: 'Test 1', zip_code: '12345', city: 'Test', management_type: 'MISCH' } });
    assert.equal(createdProperty.status(), 201);
    const property = await createdProperty.json();
    await page.goto(base + '/berechtigungen/teamrechte');
    await page.getByLabel('Objekte durchsuchen', { exact: true }).fill('Scope browser acceptance');
    await page.getByLabel('Objekt', { exact: true }).locator(`option[value="${property.id}"]`).waitFor({ state: 'attached' });
    await page.getByLabel('Objekt', { exact: true }).selectOption(property.id);
    await page.getByLabel('Bezeichnung', { exact: true }).fill('Reviewed browser rental scope');
    await page.getByLabel('Verwaltungsart', { exact: true }).selectOption('MIET');
    await page.getByLabel('Gültig ab', { exact: true }).fill('2025-01-01');
    let firstScope, scopeKey;
    await page.route('**/api/accounting-scopes', async route => {
      if (route.request().method() !== 'POST') return route.continue();
      scopeKey = route.request().headers()['idempotency-key'];
      const response = await route.fetch();
      assert.equal(response.status(), 201);
      firstScope = await response.json();
      await route.abort('failed');
      await page.unroute('**/api/accounting-scopes');
    });
    await page.getByRole('button', { name: 'Bereich verbindlich anlegen', exact: true }).click();
    await page.getByRole('alert').waitFor();
    const retryScope = page.waitForResponse(response => response.url().endsWith('/api/accounting-scopes') && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Bereich verbindlich anlegen', exact: true }).click();
    const retried = await retryScope;
    assert.equal((await retried.json()).id, firstScope.id);
    assert.equal(retried.request().headers()['idempotency-key'], scopeKey);
    const scopePage = await page.request.get(base + '/api/accounting-scopes/page?property_id=' + property.id);
    assert.equal((await scopePage.json()).items.length, 1);
    report.checks.push('lost scope reply replays one immutable scope with the same command key');
    await page.getByRole('link', { name: /Teamrechte verwalten/ }).click();
    await page.getByRole('heading', { name: 'Reviewed browser rental scope (MIET)' }).waitFor();
    const clerkContext = await browser.newContext();
    assert.equal((await clerkContext.request.post(base + '/api/auth/login', { data: { email: 'clerk@alpha.de', password: 'testpass1234' } })).status(), 200);
    const scopeUrl = base + '/api/accounting-scopes/' + firstScope.id;
    assert.equal((await clerkContext.request.get(scopeUrl)).status(), 404);
    const users = await page.request.get(base + '/api/users/page?eligible_for_scope=true&q=clerk%40alpha.de');
    const clerk = (await users.json()).items[0];
    await page.getByLabel('Teammitglied', { exact: true }).selectOption(clerk.id);
    await page.getByRole('checkbox', { name: 'Vorbereiten', exact: true }).check();
    await page.getByLabel('Begründung', { exact: true }).fill('Reviewed browser team assignment');
    let grantKey, firstGrant;
    const grantPattern = '**/api/accounting-scopes/' + firstScope.id + '/grants';
    await page.route(grantPattern, async route => {
      grantKey = route.request().headers()['idempotency-key'];
      const response = await route.fetch();
      assert.equal(response.status(), 201);
      firstGrant = await response.json();
      await route.abort('failed');
      await page.unroute(grantPattern);
    });
    await page.getByRole('button', { name: 'Freigabe erteilen', exact: true }).click();
    await page.getByRole('alert').waitFor();
    const grantRetry = page.waitForResponse(response => response.url().endsWith('/grants') && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Freigabe erteilen', exact: true }).click();
    const retry = await grantRetry;
    assert.equal((await retry.json()).id, firstGrant.id);
    assert.equal(retry.request().headers()['idempotency-key'], grantKey);
    await page.getByRole('cell', { name: 'Clerk Alpha', exact: true }).waitFor();
    assert.equal((await clerkContext.request.get(scopeUrl)).status(), 200);
    report.checks.push('lost grant reply replays one grant; exact scoped access appears');
    await page.screenshot({ path: path.join(output, 'scope-grant-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: 'Widerrufen', exact: true }).click();
    await page.locator('tbody tr td:nth-child(4)').filter({ hasText: /^Widerrufen$/ }).waitFor();
    assert.equal((await clerkContext.request.get(scopeUrl)).status(), 404);
    report.checks.push('revocation removes scope access and retains visible grant history');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForFunction(() => document.querySelector('aside').getBoundingClientRect().right <= 1);
    await page.locator('main').evaluate(node => node.scrollTo(0, 0));
    const widths = await page.locator('main').evaluate(node => ({ visible: node.clientWidth, content: node.scrollWidth }));
    assert.ok(widths.content <= widths.visible + 1);
    report.mobile = widths;
    await page.screenshot({ path: path.join(output, 'scope-grant-mobile.png') });
    await clerkContext.close();
    assert.deepEqual(report.pageErrors, []);
    assert.deepEqual(report.failedResponses, []);
    report.status = 'passed';
  } finally {
    if (page && report.status !== "passed") await page.screenshot({ path: path.join(output, "failed-state.png"), fullPage: true });
    await fs.writeFile(path.join(output, 'browser-report.json'), JSON.stringify(report, null, 2));
    await browser.close();
  }
  console.log(JSON.stringify(report));
})().catch(error => { console.error(error); process.exitCode = 1; });
